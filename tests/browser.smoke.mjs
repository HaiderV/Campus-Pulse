import assert from 'node:assert/strict';
import { mkdirSync, readFileSync } from 'node:fs';
import { chromium } from 'playwright-core';
import { createApp } from '../backend/server.mjs';

const app = createApp({ databasePath: ':memory:' });
const server = await new Promise(resolve => { const listening = app.listen(0, '127.0.0.1', () => resolve(listening)); });
const base = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser = await chromium.launch({
    headless: true,
    ...(process.env.BROWSER_PATH ? { executablePath: process.env.BROWSER_PATH } : { channel: 'msedge' }),
  });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const settled = () => page.waitForFunction(() => document.querySelector('#data-view').getAttribute('aria-busy') === 'false');
  const noOverflow = async () => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.goto(base);
  await settled();
  assert.equal(await page.locator('#stat-total').textContent(), '0');
  assert.equal(await page.locator('#empty-state').isVisible(), true);
  await page.locator('#load-demo').click();
  await page.waitForFunction(() => document.querySelector('#stat-total').textContent === '24');
  assert.equal(await page.locator('#feedback-body tr').count(), 8);
  assert.equal(await page.locator('#demo-banner').isVisible(), true);
  const chartPixels = await page.locator('canvas').evaluateAll(canvases => canvases.map(canvas => ({
    id: canvas.id, width: canvas.width, height: canvas.height,
    nonblank: canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data.some(value => value !== 0),
  })));
  assert.ok(chartPixels.every(chart => chart.width > 0 && chart.height > 0 && chart.nonblank));
  await noOverflow();
  mkdirSync('.artifacts', { recursive: true });
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: '.artifacts/dashboard-desktop.png', fullPage: true });
  await page.locator('#next-page').click();
  await page.waitForFunction(() => document.querySelector('#page-number').textContent === '2');
  await page.locator('.row-detail').first().click();
  assert.equal(await page.locator('#detail-dialog').isVisible(), true);
  await page.keyboard.press('Escape');
  await page.locator('[data-sentiment="negative"]').click();
  await page.waitForFunction(() => document.querySelector('#stat-total').textContent === '6');
  assert.equal(await page.locator('#feedback-body tr').count(), 6);
  await page.locator('#category-filter').selectOption('Food & Dining');
  await page.waitForFunction(() => document.querySelector('#stat-total').textContent === '2');
  await page.locator('#search-input').fill('does-not-exist');
  await page.waitForFunction(() => document.querySelector('#stat-total').textContent === '0');
  assert.equal(await page.locator('#empty-title').textContent(), 'No matching feedback');
  await page.locator('#clear-filters').click();
  await page.waitForFunction(() => document.querySelector('#stat-total').textContent === '24');
  await page.locator('#view-all-link').click();
  assert.equal(await page.locator('#analytics-view').isVisible(), false);
  await page.locator('.heading-actions a[href="#submit"]').click();
  await page.locator('#student-department').selectOption('Engineering');
  await page.locator('.category-option').filter({ hasText: 'Food & Dining' }).click();
  await page.locator('#feedback-text').fill('The food is terrible cold and overpriced.');
  await page.locator('#submit-button').click();
  await page.locator('#submission-success').waitFor();
  assert.equal(await page.locator('#submission-result').textContent(), 'Negative');
  await page.locator('#submission-success a').click();
  await page.waitForFunction(() => document.querySelector('#stat-total').textContent === '25');
  assert.match(await page.locator('#feedback-body tr').first().textContent(), /Anonymous/);
  await page.locator('#model-button').click();
  assert.match(await page.locator('#model-content').textContent(), /90/);
  await page.keyboard.press('Escape');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export-button').click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), 'campus-feedback.csv');
  assert.match(readFileSync(await download.path(), 'utf8'), /The food is terrible cold and overpriced/);
  await page.setViewportSize({ width: 390, height: 844 });
  await noOverflow();
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: '.artifacts/dashboard-mobile.png', fullPage: true });
  await page.locator('#menu-button').click();
  assert.equal(await page.locator('#sidebar').evaluate(element => element.classList.contains('open')), true);
  await page.locator('.nav-link[data-view="submit"]').click();
  assert.equal(await page.locator('#sidebar').evaluate(element => element.classList.contains('open')), false);
  await page.locator('#submit-another').click();
  await noOverflow();
  await page.screenshot({ path: '.artifacts/submit-mobile.png', fullPage: true });
  await page.locator('#student-department').selectOption('Other');
  await page.locator('#feedback-text').fill('<img src=x onerror=alert(1)> The teachers are excellent and helpful.');
  await page.locator('#submit-button').click();
  await page.locator('#submission-success').waitFor();
  await page.locator('#submission-success a').click();
  await page.waitForFunction(() => document.querySelector('#stat-total').textContent === '26');
  assert.equal(await page.locator('#feedback-body img').count(), 0);
  assert.match(await page.locator('#feedback-body tr').first().textContent(), /<img src=x/);
  await page.locator('#remove-demo').click();
  await page.locator('#confirm-remove').click();
  await page.waitForFunction(() => document.querySelector('#stat-total').textContent === '2');
  assert.equal(await page.locator('#demo-banner').isVisible(), false);
  assert.equal(await page.locator('#feedback-body tr').count(), 2);
  await page.setViewportSize({ width: 320, height: 740 });
  await noOverflow();
  await page.route('**/api/config', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Temporary test outage.' }) }));
  await page.goto(base);
  await page.locator('#load-error').waitFor();
  await page.unroute('**/api/config');
  await page.locator('#retry-button').click();
  await page.waitForFunction(() => document.querySelector('#stat-total').textContent === '2');
  assert.equal(await page.locator('#load-error').isVisible(), false);
  await page.goto(base + '/#submit');
  await page.locator('.category-option').first().waitFor();
  await page.locator('#menu-button').click();
  await page.locator('.nav-link[data-view="dashboard"]').click();
  await page.waitForFunction(() => document.querySelector('#stat-total').textContent === '2');
  assert.ok(await page.locator('#trend-chart').evaluate(canvas => canvas.width > 0 && canvas.height > 0));
  assert.deepEqual(errors, []);
  console.log('PASS: empty state, demo loading, chart pixels, pagination, details, sentiment/category/search filters, anonymous submission, model dialog, CSV download, mobile navigation, XSS escaping, sample removal, startup error recovery, and direct-link navigation.');
  console.log('PASS: no page overflow at 1440px, 390px, or 320px; no browser JavaScript errors.');
  console.log('Chart pixel checks:', JSON.stringify(chartPixels));
  console.log('Screenshots saved to .artifacts/.');
} finally {
  await browser?.close();
  await new Promise(resolve => server.close(resolve));
  app.locals.close();
}
